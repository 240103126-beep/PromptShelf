for (const format of ['md', 'zip'] as const) {
  test(`export ${format} downloads actual collection content`, async ({ page, data }) => {
    const collection = await data.collection(`export ${format}`)
    const item = await data.item(`exported ${format}`, { collectionIds: [collection.id], notes: 'Important export note' })
    await page.goto('/app/export')
    await page.getByRole('checkbox', { name: collection.name, exact: true }).check()
    await page.getByRole('radio', { name: format === 'md' ? 'Single .md file' : 'ZIP of .md files', exact: true }).click()
    const downloadPromise = page.waitForEvent('download')
    await page.getByRole('button', { name: 'Export', exact: true }).click()
    const download = await downloadPromise
    expect(download.suggestedFilename()).toMatch(new RegExp(`\\.${format}$`))
    const contents = await readFile((await download.path())!)
    if (format === 'md') {
      expect(contents.toString()).toContain(item.title)
      expect(contents.toString()).toContain('Important export note')
    } else {
      const zip = await JSZip.loadAsync(contents)
      const files = Object.values(zip.files).filter(f => f.name.endsWith('.md') && !f.dir)
      const texts = await Promise.all(files.map(f => f.async('string')))
      expect(texts.join('\n')).toContain(item.title)
      expect(texts.join('\n')).toContain('Important export note')
      expect(texts.some(t => t.startsWith('---\n'))).toBeTruthy()
    }
    await expect(page.getByText(/Exported 1 items as/)).toBeVisible()
  })
}

