for (const feature of ['title', 'summary', 'tags', 'category', 'improve'] as const) {
  test(`AI editor ${feature} suggestions can be applied`, async ({ page, data }) => {
    await page.goto('/app/new')
    await page.getByLabel('Prompt', { exact: true }).fill('Explain SQL indexes and give three examples for beginners')
    const action = { title: 'Suggest title', summary: 'Summarize', tags: 'Suggest tags', category: 'Suggest category', improve: 'Improve prompt' }[feature]
    await page.getByRole('button', { name: action, exact: true }).click()
    const aside = page.locator('aside').filter({ hasText: 'AI assist' })
    if (feature === 'title') {
      const suggestion = aside.locator('button.text-left').first()
      await expect(suggestion).toBeVisible()
      const text = await suggestion.innerText()
      await suggestion.click()
      await expect(page.getByLabel('Title', { exact: true })).toHaveValue(text)
    } else if (feature === 'summary') {
      await aside.getByRole('button', { name: 'Add to notes', exact: true }).click()
      await expect(page.getByLabel('Notes', { exact: true })).not.toBeEmpty()
    } else if (feature === 'improve') {
      await aside.getByRole('button', { name: 'Use this', exact: true }).click()
      await expect(page.getByLabel('Prompt', { exact: true })).not.toHaveValue('Explain SQL indexes and give three examples for beginners')
    } else {
      const suggestion = aside.locator('button').filter({ hasText: feature === 'tags' ? /^\+ / : /^(Development|Writing|Learning|Productivity|General)$/ }).first()
      await expect(suggestion).toBeVisible()
      await suggestion.click()
      if (feature === 'category') await expect(page.getByLabel('Category', { exact: true })).not.toHaveValue('')
      else await expect(page.locator('main button[aria-pressed="true"]')).not.toHaveCount(0)
    }
  })
}

